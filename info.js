/* =================================
   SEARCH
================================= */

const searchInput =
    document.getElementById(
        "searchInput"
    );


const searchBtn =
    document.getElementById(
        "searchBtn"
    );


function searchMovie() {

    const query =
        searchInput.value.trim();


    if (query === "") {

        window.location.href =
            "index.html";

        return;

    }


    window.location.href =
        "index.html?search=" +
        encodeURIComponent(query);

}


if (searchBtn) {

    searchBtn.addEventListener(
        "click",
        searchMovie
    );

}


if (searchInput) {

    searchInput.addEventListener(
        "keydown",
        event => {

            if (
                event.key === "Enter"
            ) {

                searchMovie();

            }

        }
    );

}
